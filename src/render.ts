import { chmodSync, writeFileSync } from 'node:fs'
import type { Manifest, SecretStore } from './types.js'

export interface RenderResult {
  /** Resolved KEY -> value map (op:// refs resolved to concrete secret values). */
  env: Record<string, string>
  /** Keys whose manifest value was an op:// reference (resolved from 1Password). */
  secretKeys: string[]
  /** Keys whose manifest value was a plain literal. */
  literalKeys: string[]
}

export interface RenderOptions {
  /** Optional project block to merge on top of `shared` (project wins). */
  project?: string
  /** Secret store used to resolve op:// references. */
  secrets: SecretStore
}

/**
 * Resolve a manifest into a concrete env map: `shared` merged with an
 * optional project block, each op:// value resolved through the SecretStore.
 * Pure apart from the injected SecretStore, so it is unit-testable without
 * touching the real `op`.
 */
export async function computeRender(
  manifest: Manifest,
  options: RenderOptions,
): Promise<RenderResult> {
  const { project, secrets } = options
  if (project && !manifest.projects[project]) {
    throw new Error(`Project "${project}" not found in manifest`)
  }
  const projectVars = project ? manifest.projects[project] : {}
  const merged: Record<string, string> = { ...manifest.shared, ...projectVars }

  const env: Record<string, string> = {}
  const secretKeys: string[] = []
  const literalKeys: string[] = []
  for (const [key, value] of Object.entries(merged)) {
    if (secrets.canResolve(value)) {
      env[key] = await secrets.resolve(value)
      secretKeys.push(key)
    } else {
      env[key] = value
      literalKeys.push(key)
    }
  }
  return { env, secretKeys, literalKeys }
}

/**
 * Format a resolved env map as an unquoted `KEY=value` dotenv, matching the
 * hand-written .env style. Throws on newline-bearing values, which an
 * unquoted dotenv cannot represent.
 */
export function renderDotenv(env: Record<string, string>): string {
  const lines = [
    '# Generated by `environment-manager render` — do not hand-edit.',
    '# Regenerate from .environment-manager/<name>.manifest.yaml + 1Password.',
    '',
  ]
  for (const [key, value] of Object.entries(env)) {
    if (value.includes('\n')) {
      throw new Error(`Value for ${key} contains a newline; cannot write an unquoted dotenv`)
    }
    lines.push(`${key}=${value}`)
  }
  return `${lines.join('\n')}\n`
}

/** Write the rendered dotenv to disk with owner-only (0600) permissions. */
export function writeEnvFile(outPath: string, env: Record<string, string>): void {
  writeFileSync(outPath, renderDotenv(env), { mode: 0o600 })
  // mode only applies when the file is created; an existing file keeps its own.
  chmodSync(outPath, 0o600)
}
