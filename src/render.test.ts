import { describe, it, expect, vi, beforeEach } from 'vitest'
import { chmodSync, writeFileSync } from 'node:fs'
import { computeRender, renderDotenv, writeEnvFile } from './render.js'
import type { Manifest, SecretStore } from './types.js'

vi.mock('node:fs', () => ({
  writeFileSync: vi.fn(),
  chmodSync: vi.fn(),
}))

const mockedWriteFile = vi.mocked(writeFileSync)

function mockSecrets(): SecretStore {
  return {
    canResolve: (v: string) => v.startsWith('op://'),
    resolve: vi.fn(async (uri: string) => `resolved-${uri}`),
    write: vi.fn(),
  }
}

describe('computeRender', () => {
  it('resolves op:// values and passes literals through, classifying each', async () => {
    const manifest: Manifest = {
      shared: { APP_DOMAIN: 'example.com', JWT: 'op://Vault/item/field' },
      projects: {},
    }
    const result = await computeRender(manifest, { secrets: mockSecrets() })
    expect(result.env).toEqual({
      APP_DOMAIN: 'example.com',
      JWT: 'resolved-op://Vault/item/field',
    })
    expect(result.secretKeys).toEqual(['JWT'])
    expect(result.literalKeys).toEqual(['APP_DOMAIN'])
  })

  it('merges a named project on top of shared (project overrides shared, order preserved)', async () => {
    const manifest: Manifest = {
      shared: { A: 'shared-a', C: 'shared-c' },
      projects: { prod: { A: 'proj-a', D: 'op://x/y/z' } },
    }
    const result = await computeRender(manifest, { project: 'prod', secrets: mockSecrets() })
    expect(result.env).toEqual({ A: 'proj-a', C: 'shared-c', D: 'resolved-op://x/y/z' })
    expect(Object.keys(result.env)).toEqual(['A', 'C', 'D'])
    expect(result.secretKeys).toEqual(['D'])
  })

  it('renders only shared when no project is given', async () => {
    const manifest: Manifest = {
      shared: { A: 'a' },
      projects: { prod: { SHOULD_NOT: 'appear' } },
    }
    const result = await computeRender(manifest, { secrets: mockSecrets() })
    expect(result.env).toEqual({ A: 'a' })
  })

  it('throws when the named project is missing', async () => {
    const manifest: Manifest = { shared: {}, projects: {} }
    await expect(
      computeRender(manifest, { project: 'nope', secrets: mockSecrets() }),
    ).rejects.toThrow(/nope/)
  })
})

describe('renderDotenv', () => {
  it('emits a generated-file header and KEY=value lines, trailing newline', () => {
    const out = renderDotenv({ FOO: 'bar', BAZ: 'https://x.example' })
    expect(out.startsWith('# Generated by')).toBe(true)
    expect(out).toContain('\nFOO=bar\n')
    expect(out).toContain('\nBAZ=https://x.example\n')
    expect(out.endsWith('\n')).toBe(true)
  })

  it('names the manifest and the command that regenerates it', () => {
    const out = renderDotenv({ FOO: 'bar' }, 'production')
    expect(out).toContain('.environment-manager/production.manifest.yaml')
    expect(out).toContain('environment-manager render production')
    expect(out).not.toContain('<name>')
  })

  it('refuses to write a value containing a newline', () => {
    expect(() => renderDotenv({ BAD: 'line1\nline2' })).toThrow(/BAD/)
  })
})

describe('writeEnvFile', () => {
  beforeEach(() => {
    mockedWriteFile.mockClear()
  })

  it('writes the rendered dotenv at mode 0600', () => {
    writeEnvFile('/tmp/out.env', { FOO: 'bar' })
    expect(mockedWriteFile).toHaveBeenCalledTimes(1)
    const [path, content, opts] = mockedWriteFile.mock.calls[0]
    expect(path).toBe('/tmp/out.env')
    expect(String(content)).toContain('FOO=bar')
    expect(opts).toEqual({ mode: 0o600 })
  })

  it('tightens an existing file to 0600, since mode only applies on create', () => {
    writeEnvFile('/tmp/out.env', { FOO: 'bar' })
    expect(vi.mocked(chmodSync)).toHaveBeenCalledWith('/tmp/out.env', 0o600)
  })
})
